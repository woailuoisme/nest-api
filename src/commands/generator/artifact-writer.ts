import { existsSync, mkdirSync, readdirSync, readFileSync, rmdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

import { Logger } from '@nestjs/common';
import { compact } from 'es-toolkit';

import { type RenderedArtifact, TEMPLATE_FILES, TemplateRenderer } from './template-renderer';
import type { ModuleScope, TemplateContext } from './types';
import { toCamelCase, toPascalCase } from './utils/string.util';

/** File header marker distinguishing generated modules from hand-written ones */
export const GENERATED_MARKER = '// @generated crud:generate';

/** Delete result — deleted / skipped / error details */
export interface DeleteResult {
  deleted: string[];
  skipped: string[];
  errors: string[];
}

const logger = new Logger('ArtifactWriter');

// ─── 文本增量编辑（注册 / 反注册共用，保证生命周期对称）───────────

const IMPORTS_ARRAY_PATTERN = /imports: \[([^\]]*)\]/;
const CLIENT_MODULES_PATTERN = /export const CLIENT_FEATURE_MODULES = \[([^\]]*)\]/;
const FEATURE_MODULES_PATTERN = /export const FEATURE_MODULES = \[([^\]]*)\]/;

/** `[A, B]` 内容 → 去空白后的条目（空项丢弃） */
function parseListItems(list: string): string[] {
  return compact(list.split(',').map((item) => item.trim()));
}

/** 重写首个匹配的数组字面量；`prefix` 含 `[`，条目统一以 `, ` 连接 */
function updateArrayLiteral(
  content: string,
  pattern: RegExp,
  prefix: string,
  update: (items: string[]) => string[],
): string {
  return content.replace(pattern, (_matched, list: string) => `${prefix}${update(parseListItems(list)).join(', ')}]`);
}

/** 在最后一条 import 之后插入新 import（保持 import 区聚拢） */
function insertImportLine(content: string, importLine: string): string {
  const lines = content.split('\n');
  const lastImportIdx = lines.reduce((last, line, idx) => (line.startsWith('import ') ? idx : last), -1);
  lines.splice(lastImportIdx + 1, 0, importLine);
  return lines.join('\n');
}

/** 删除整行内容匹配的行（import / export 声明的反向操作） */
function dropLines(content: string, ...targets: string[]): string {
  return content
    .split('\n')
    .filter((line) => !targets.includes(line.trim()))
    .join('\n');
}

/** FEATURE_MODULES 中把新模块插到 AdminModule 之前（管理面聚合保持在列表末位） */
function insertBeforeAdminModule(items: string[], moduleName: string): string[] {
  const adminIdx = items.indexOf('AdminModule');
  if (adminIdx === -1) return [...items, moduleName];

  const next = [...items];
  next.splice(adminIdx, 0, moduleName);
  return next;
}

// ─── 文件系统辅助 ────────────────────────────────────────────

/** Read the first line of a file */
function readFirstLine(filePath: string): string | null {
  try {
    return readFileSync(filePath, 'utf8').split('\n')[0]?.trim() || null;
  } catch {
    return null;
  }
}

/** Clean up empty directories after deleting a generated module */
function cleanupEmptyDirs(projectRoot: string, ctx: TemplateContext): void {
  const dirsToCheck = [
    join(projectRoot, `tests/unit/${ctx.featureModulePath}`),
    join(projectRoot, `src/${ctx.featureModulePath}`),
  ];

  for (const dir of dirsToCheck) {
    try {
      if (existsSync(dir) && readdirSync(dir).length === 0) {
        rmdirSync(dir);
        logger.log(`  removed empty directory: ${relative(projectRoot, dir)}`);
      }
    } catch {
      // ignored
    }
  }
}

/**
 * Artifact safe writer: conflict detection, idempotent registration and cleanup
 */
export const ArtifactWriter = {
  /**
   * Detect pre-existing generated files (files without the @generated marker are hand-written and never overwritten).
   */
  detectConflicts(projectRoot: string, ctx: TemplateContext): string[] {
    const conflicts: string[] = [];

    for (const entry of TEMPLATE_FILES) {
      const outputPath = join(projectRoot, entry.output(ctx));
      if (existsSync(outputPath)) {
        const firstLine = readFirstLine(outputPath);
        if (firstLine?.startsWith(GENERATED_MARKER)) {
          continue;
        }
        conflicts.push(
          `File exists and was not generated by crud:generate, refusing to overwrite: ${entry.output(ctx)}`,
        );
      }
    }

    return conflicts;
  },

  /**
   * Safely write rendered artifacts to disk
   */
  writeArtifacts(projectRoot: string, artifacts: RenderedArtifact[]): string[] {
    const writtenFiles: string[] = [];

    for (const artifact of artifacts) {
      const fullPath = join(projectRoot, artifact.outputPath);
      mkdirSync(dirname(fullPath), { recursive: true });
      writeFileSync(fullPath, artifact.content, 'utf8');
      writtenFiles.push(artifact.outputPath);
      logger.log(`  generated ${artifact.outputPath}`);
    }

    return writtenFiles;
  },

  /**
   * Safely delete a generated CRUD module.
   * Only files whose first line contains the @generated marker are removed, protecting hand-written code.
   */
  deleteModule(projectRoot: string, name: string, scope?: ModuleScope): DeleteResult {
    const featureName = toCamelCase(name);
    const scopesToCheck: ModuleScope[] = scope ? [scope] : ['admin', 'client'];
    const result: DeleteResult = {
      deleted: [],
      skipped: [],
      errors: [],
    };

    // 1. Walk generated files matching the scope and delete them
    for (const s of scopesToCheck) {
      const ctx = TemplateRenderer.buildContext(featureName, [], s);
      for (const entry of TEMPLATE_FILES) {
        const outputPath = join(projectRoot, entry.output(ctx));
        if (!existsSync(outputPath)) {
          continue;
        }

        const firstLine = readFirstLine(outputPath);
        if (!firstLine?.startsWith(GENERATED_MARKER)) {
          result.skipped.push(`${entry.output(ctx)} (not a generated file, skipped)`);
          continue;
        }

        try {
          unlinkSync(outputPath);
          result.deleted.push(entry.output(ctx));
        } catch {
          result.errors.push(`Delete failed: ${entry.output(ctx)}`);
        }
      }

      // Clean up empty directories
      cleanupEmptyDirs(projectRoot, ctx);
    }

    // 2. Remove the export line from schema/index.ts (only when the schema file is already deleted or absent)
    const schemaFilePath = join(projectRoot, 'src', 'database', 'drizzle', 'schema', `${featureName}.schema.ts`);
    if (!existsSync(schemaFilePath)) {
      try {
        ArtifactWriter.updateSchemaExport(projectRoot, featureName, 'unregister');
        result.deleted.push(`src/database/drizzle/schema/index.ts (removed ${featureName} export)`);
      } catch (err) {
        result.errors.push(`Failed to remove schema export: ${(err as Error).message}`);
      }
    }

    // 3. Only when deleting the admin scope, remove the module registration from AdminModule (idempotent)
    if (!scope || scope === 'admin') {
      try {
        ArtifactWriter.updateAdminModuleExport(projectRoot, featureName, 'unregister');
      } catch (err) {
        result.errors.push(`Failed to remove AdminModule registration: ${(err as Error).message}`);
      }
    }

    // 4. Only when deleting the client scope, remove the client module registration from src/features/index.ts (idempotent)
    if (!scope || scope === 'client') {
      try {
        ArtifactWriter.updateClientModuleExport(projectRoot, featureName, 'unregister');
      } catch (err) {
        result.errors.push(`Failed to remove Client API registration: ${(err as Error).message}`);
      }
    }

    return result;
  },

  /**
   * Add/remove the schema export line for a feature (idempotent).
   * @param action 'register' adds the export | 'unregister' removes it
   */
  updateSchemaExport(projectRoot: string, featureName: string, action: 'register' | 'unregister'): void {
    const indexPath = join(projectRoot, 'src', 'database', 'drizzle', 'schema', 'index.ts');
    const content = readFileSync(indexPath, 'utf8');
    const exportLine = `export * from './${featureName}.schema';`;
    const present = content.includes(exportLine);

    if (action === 'register' ? present : !present) return;

    const next = action === 'register' ? `${content.trimEnd()}\n${exportLine}\n` : dropLines(content, exportLine);

    writeFileSync(indexPath, next, 'utf8');
    logger.log(`  ${action === 'register' ? 'registered' : 'removed'} schema export: ${exportLine}`);
  },

  /**
   * Add/remove a feature module registration in AdminModule (idempotent).
   * The import line and imports array entry are maintained together, keeping the generate/delete lifecycle fully symmetric.
   */
  updateAdminModuleExport(projectRoot: string, featureName: string, action: 'register' | 'unregister'): void {
    const adminModulePath = join(projectRoot, 'src', 'features', 'admin', 'admin.module.ts');
    if (!existsSync(adminModulePath)) return;

    const content = readFileSync(adminModulePath, 'utf8');
    const moduleName = `${toPascalCase(featureName)}Module`;
    const importLine = `import { ${moduleName} } from './${featureName}/${featureName}.module';`;
    const present = content.includes(importLine);

    if (action === 'register' ? present : !present) return;

    const next =
      action === 'register'
        ? updateArrayLiteral(insertImportLine(content, importLine), IMPORTS_ARRAY_PATTERN, 'imports: [', (items) => [
            ...items,
            moduleName,
          ])
        : updateArrayLiteral(dropLines(content, importLine), IMPORTS_ARRAY_PATTERN, 'imports: [', (items) =>
            items.filter((item) => item !== moduleName),
          );

    writeFileSync(adminModulePath, next, 'utf8');
    logger.log(`  ${action === 'register' ? 'registered' : 'removed'} AdminModule module: ${moduleName}`);
  },

  /**
   * Add/remove a client feature module registration and export in src/features/index.ts (idempotent).
   */
  updateClientModuleExport(projectRoot: string, featureName: string, action: 'register' | 'unregister'): void {
    const apiIndexPath = join(projectRoot, 'src', 'features', 'index.ts');
    if (!existsSync(apiIndexPath)) return;

    const content = readFileSync(apiIndexPath, 'utf8');
    const moduleName = `${toPascalCase(featureName)}Module`;
    const importLine = `import { ${moduleName} } from '@/features/client/${featureName}/${featureName}.module';`;
    const exportLine = `export * from '@/features/client/${featureName}/${featureName}.module';`;
    const present = content.includes(importLine);

    if (action === 'register' ? present : !present) return;

    let next: string;
    if (action === 'register') {
      next = insertImportLine(content, importLine);
      next = updateArrayLiteral(next, CLIENT_MODULES_PATTERN, 'export const CLIENT_FEATURE_MODULES = [', (items) => [
        ...items,
        moduleName,
      ]);
      next = updateArrayLiteral(next, FEATURE_MODULES_PATTERN, 'export const FEATURE_MODULES = [', (items) =>
        insertBeforeAdminModule(items, moduleName),
      );
      next = `${next.trimEnd()}\n${exportLine}\n`;
    } else {
      next = dropLines(content, importLine, exportLine);
      next = updateArrayLiteral(next, CLIENT_MODULES_PATTERN, 'export const CLIENT_FEATURE_MODULES = [', (items) =>
        items.filter((item) => item !== moduleName),
      );
      next = updateArrayLiteral(next, FEATURE_MODULES_PATTERN, 'export const FEATURE_MODULES = [', (items) =>
        items.filter((item) => item !== moduleName),
      );
    }

    writeFileSync(apiIndexPath, next, 'utf8');
    logger.log(`  ${action === 'register' ? 'registered' : 'removed'} Client API module: ${moduleName}`);
  },

  /**
   * Register/unregister a module according to its scope
   */
  updateModuleRegistration(
    projectRoot: string,
    featureName: string,
    scope: ModuleScope,
    action: 'register' | 'unregister',
  ): void {
    if (scope === 'admin') {
      ArtifactWriter.updateAdminModuleExport(projectRoot, featureName, action);
    } else {
      ArtifactWriter.updateClientModuleExport(projectRoot, featureName, action);
    }
  },
};
